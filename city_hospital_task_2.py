"""### 2. Implement the Ingestion and Indexing Pipeline
We will write a python workflow to:
1. Read each `.txt` file.
2. Chunk the texts into approximately 200‑token segments using the sentence-transformers tokenizer.
3. Compute embeddings using the `sentence-transformers/all-MiniLM-L6-v2` model.
4. Save the embeddings in a FAISS index.
5. Persist the FAISS index to `index.faiss` and the chunks' metadata to `metadata.json`.
"""

import glob
import json
import numpy as np
import faiss
from sentence_transformers import SentenceTransformer
from tqdm import tqdm

# Initialize the sentence-transformer model
model_name = 'sentence-transformers/all-MiniLM-L6-v2'
model = SentenceTransformer(model_name)
tokenizer = model.tokenizer

chunks_metadata = []
embeddings_list = []

# Get all text files
file_paths = glob.glob("data/*.txt")

for file_path in tqdm(file_paths, desc="Processing files"):
    filename = os.path.basename(file_path)
    with open(file_path, 'r', encoding='utf-8') as f:
        text = f.read()

    # Tokenize the whole document text
    tokens = tokenizer.encode(text, add_special_tokens=False)

    # Set chunk size (200 tokens) and overlap if desired (e.g., 20 tokens)
    chunk_size = 200
    overlap = 20

    i = 0
    while i < len(tokens):
        # Slice 200 tokens
        chunk_tokens = tokens[i : i + chunk_size]
        chunk_text = tokenizer.decode(chunk_tokens, skip_special_tokens=True)

        # Create embedding
        embedding = model.encode(chunk_text)
        embeddings_list.append(embedding)

        # Save metadata entry
        chunks_metadata.append({
            "source_filename": filename,
            "chunk_offset": i,
            "chunk_text": chunk_text
        })

        # Move window forward
        i += (chunk_size - overlap)
        if i >= len(tokens) - overlap:  # break if remaining tokens are negligible
            break

# Convert embeddings to numpy array
embeddings_arr = np.array(embeddings_list).astype('float32')

# Dimension of 'all-MiniLM-L6-v2' is 384
dimension = embeddings_arr.shape[1]

# Create FAISS Index
index = faiss.IndexFlatL2(dimension)
index.add(embeddings_arr)

# Save index and metadata
faiss.write_index(index, "index.faiss")
with open("metadata.json", "w", encoding="utf-8") as f:
    json.dump(chunks_metadata, f, indent=4)

print(f"Successfully indexed {len(chunks_metadata)} chunks.")
print("Saved 'index.faiss' and 'metadata.json'.")

"""### 3. Verification Script
Now we write a quick verification routine that loads the FAISS index and the metadata to execute a sample search query.
"""

def search_vector_store(query, top_k=3):
    # 1. Load FAISS index
    index = faiss.read_index("index.faiss")

    # 2. Load Metadata
    with open("metadata.json", "r", encoding="utf-8") as f:
        metadata = json.load(f)

    # 3. Embed Query
    query_embedding = model.encode([query]).astype('float32')

    # 4. Query FAISS
    distances, indices = index.search(query_embedding, top_k)

    # 5. Output results
    print(f"Query: {query}\n")
    for idx, dist in zip(indices[0], distances[0]):
        if idx < len(metadata):
            meta = metadata[idx]
            print(f"[Distance: {dist:.4f}] File: {meta['source_filename']} (Offset: {meta['chunk_offset']})")
            print(f"Content: {meta['chunk_text']}\n")

# Let's run a test query
