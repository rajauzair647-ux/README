"""### Step 5: Evaluation Script & CSV Export
We will measure precision@k, simulated latency, and token cost calculation. Finally, we save this analysis to an evaluation CSV.
"""

import pandas as pd

# Mock dataset of benchmark questions
benchmark_questions = [
    {"question": "What is FastAPI?", "expected_docs": ["doc_0"]},
    {"question": "Explain FAISS index capabilities.", "expected_docs": ["doc_1"]},
    {"question": "What are RAG architectures?", "expected_docs": ["doc_2"]}
]

evals = []

for bq in benchmark_questions:
    start_time = time.time()

    # Simulate retrieval
    np.random.seed(sum(ord(c) for c in bq["question"]))
    query_vector = np.random.randn(128).astype('float32')
    retrieved = retrieve_top_k(query_vector, k=2)

    retrieved_ids = [r["id"] for r in retrieved]

    # Calculate precision@k
    relevant_retrieved = sum([1 for r_id in retrieved_ids if r_id in bq["expected_docs"]])
    precision_at_k = relevant_retrieved / len(retrieved_ids) if len(retrieved_ids) > 0 else 0.0

    latency = (time.time() - start_time) * 1000
    token_cost = 0.0015 * (150 / 1000) # Mock model cost calculation ($/1k tokens)

    evals.append({
        "question": bq["question"],
        "precision_at_k": precision_at_k,
        "latency_ms": round(latency, 2),
        "token_cost_usd": round(token_cost, 6)
    })

df_eval = pd.DataFrame(evals)
# Save to csv
df_eval.to_csv("evaluation_report.csv", index=False)
