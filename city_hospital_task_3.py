"""### Step 2: Implement mock FAISS Index and Documents
To keep our environment self-contained, let's create a mockup FAISS index containing pre-defined passage chunks with IDs for our RAG system.
"""

import faiss
import numpy as np
import json

# Mock documents database
documents = {
    0: {"id": "doc_0", "text": "FastAPI is a modern, fast (high-performance), web framework for building APIs with Python 3.8+ based on standard Python type hints.", "source": "FastAPI Docs"},
    1: {"id": "doc_1", "text": "FAISS (Facebook AI Similarity Search) is a library for efficient similarity search and clustering of dense vectors.", "source": "FAISS Docs"},
    2: {"id": "doc_2", "text": "Retrieval-Augmented Generation (RAG) improves LLM responses by fetching relevant documents before generating text.", "source": "RAG Overview"},
    3: {"id": "doc_3", "text": "To implement citation in RAG, system prompts must instruct the LLM to format its answers referencing specific document IDs.", "source": "Prompt Engineering Guide"}
}

# Quick helper to generate a dummy 128-dim vector space for matching
dimension = 128
index = faiss.IndexFlatL2(dimension)

# Generate random vectors representing document semantic representations
np.random.seed(42)
doc_vectors = np.random.randn(len(documents), dimension).astype('float32')
index.add(doc_vectors)

def retrieve_top_k(query_vector, k=2):
    distances, indices = index.search(np.array([query_vector]).astype('float32'), k)
    results = []
    for idx in indices[0]:
        if idx in documents:
            results.append(documents[idx])
    return results

print(f"Created mock FAISS store with {index.ntotal} documents.")

"""### Step 3: Define the FastAPI Application
Now we'll define the FastAPI application incorporating our simulated FAISS search, building a citation prompt, and generating a structured response.
"""

from fastapi import FastAPI, HTTPException
from pydantic import BaseModel
from typing import List, Dict, Any
import time

app = FastAPI(title="RAG Citation Service")

class QueryRequest(BaseModel):
    question: str
    k: int = 2

class Citation(BaseModel):
    doc_id: str
    source: str
    snippet: str

class QueryResponse(BaseModel):
    answer: str
    sources: List[Citation]
    latency_ms: float

@app.get("/health")
def health():
    return {"status": "ok"}

@app.post("/answer", response_model=QueryResponse)
def answer_endpoint(request: QueryRequest):
    start_time = time.time()

    # Generate a dummy query vector (in production, use an embedding model like text-embedding-3-small)
    np.random.seed(sum(ord(c) for c in request.question))
    query_vector = np.random.randn(128).astype('float32')

    # 1. Retrieve top-k chunks
    retrieved_chunks = retrieve_top_k(query_vector, k=request.k)

    # 2. Build system prompt instructing LLM to cite sources
    context_str = "\n".join([
        f"[ID: {chunk['id']}] (Source: {chunk['source']}) {chunk['text']}"
        for chunk in retrieved_chunks
    ])

    system_prompt = (
        "You are a precise assistant. Answer the user's question using ONLY the provided context blocks. "
        "For every fact you state, you MUST cite its source using the format [ID]. \n\n"
        f"Context:\n{context_str}"
    )

    # 3. Call Simulated / Mock LLM API locally to show full schema integration cleanly
    # In production, call: client.chat.completions.create(model='gpt-3.5-turbo', messages=[...])
    answer = f"Based on our documents, the context indicates that: {retrieved_chunks[0]['text']} [{retrieved_chunks[0]['id']}]"

    citations = [
        Citation(doc_id=chunk['id'], source=chunk['source'], snippet=chunk['text'])
        for chunk in retrieved_chunks
    ]

    latency_ms = (time.time() - start_time) * 1000

    return QueryResponse(
        answer=answer,
        sources=citations,
        latency_ms=round(latency_ms, 2)
    )

