import time
import json
import random
from sklearn.model_selection import train_test_split
from sklearn.metrics import accuracy_score, precision_recall_fscore_support

# --- 1. Mock Labeled Dataset & Classification Function ---
# In production, replace this mock function with your actual LLM or model API call.
def classify_text(text):
    """
    Mock classifier that simulates model inference.
    Expects input text and returns a predicted label: 'positive', 'negative', or 'neutral'.
    """
    # Simulate minor processing latency (target is < 500 ms)
    time.sleep(random.uniform(0.05, 0.2))

    # Basic rules to simulate classification
    text_lower = text.lower()
    if "great" in text_lower or "love" in text_lower or "awesome" in text_lower:
        return "positive"
    elif "bad" in text_lower or "hate" in text_lower or "terrible" in text_lower:
        return "negative"
    else:
        return "neutral"

# Seed dataset for demonstration
dataset = [
    {"text": "I love this product, it is absolutely great!", "label": "positive"},
    {"text": "This was the worst experience ever, hate it.", "label": "negative"},
    {"text": "It was okay, nothing special, pretty average.", "label": "neutral"},
    {"text": "An awesome tool that saved me hours of work.", "label": "positive"},
    {"text": "Terrible customer service and bad quality.", "label": "negative"},
    {"text": "The product arrived on time and works as expected.", "label": "neutral"},
    {"text": "Highly recommended, great quality!", "label": "positive"},
    {"text": "I do not like this, very bad design.", "label": "negative"},
    {"text": "It performs fine under normal conditions.", "label": "neutral"},
    {"text": "Simply amazing and beautiful design.", "label": "positive"}
]

# --- 2. Train/Test Split ---
texts = [item["text"] for item in dataset]
labels = [item["label"] for item in dataset]

# Split into train and test sets (80/20 split)
X_train, X_test, y_train, y_test = train_test_split(
    texts, labels, test_size=0.3, random_state=42
)

print(f"Train size: {len(X_train)}, Test size: {len(X_test)}")

# --- 3. Run Evaluation & Compute Metrics ---
y_pred = []
latencies = []

for text in X_test:
    start_time = time.perf_counter()
    pred = classify_text(text)
    end_time = time.perf_counter()

    y_pred.append(pred)
    latencies.append((end_time - start_time) * 1000) # record in milliseconds

# Compute metrics using sklearn
accuracy = accuracy_score(y_test, y_pred)
precision, recall, f1, _ = precision_recall_fscore_support(
    y_test, y_pred, average='weighted', zero_division=0
)
avg_latency = sum(latencies) / len(latencies)

metrics = {
    "accuracy": accuracy,
    "precision": precision,
    "recall": recall,
    "f1_score": f1,
    "average_latency_ms": avg_latency
}

# Save metrics to JSON
with open("metrics.json", "w") as f:
    json.dump(metrics, f, indent=4)

print("--- Evaluation Suite Summary ---")
print(json.dumps(metrics, indent=4))
assert accuracy >= 0.80, f"Warning: Accuracy is {accuracy * 100:.1f}%, which is below the 80% target!"

# --- 4. Latency Benchmark Check ---
print(f"Average Latency: {avg_latency:.2f} ms")
if avg_latency < 500:
    print("PASSED: Latency is under the 500 ms limit.")
else:
    print("FAILED: Latency exceeded 500 ms target!")

