import re
import json
import faiss
import numpy as np
from sentence_transformers import SentenceTransformer

# 1. Initialize sentence-transformers model
model = SentenceTransformer('sentence-transformers/all-MiniLM-L6-v2')

# 2. Simple chunker targeting ~200 token pieces
def chunk_text(text, max_tokens=200):
    # Simple tokenization by whitespace split
    words = text.split()
    chunks = []
    for i in range(0, len(words), max_tokens):
        chunk_words = words[i:i + max_tokens]
        chunks.append(" ".join(chunk_words))
    return chunks

all_chunks = []
metadata = []

# 3. Read and process files
for filename in sorted(os.listdir('data')):
    if filename.endswith('.txt'):
        filepath = os.path.join('data', filename)
        with open(filepath, 'r', encoding='utf-8') as f:
            text = f.read()

        chunks = chunk_text(text, max_tokens=200)
        for offset, chunk in enumerate(chunks):
            all_chunks.append(chunk)
            metadata.append({
                "source": filename,
                "offset": offset,
                "text": chunk
            })

# 4. Compute embeddings
embeddings = model.encode(all_chunks, show_progress_bar=True)
embeddings = np.array(embeddings).astype('float32')

# 5. Build and save FAISS index
dimension = embeddings.shape[1]
index = faiss.IndexFlatL2(dimension)
index.add(embeddings)

# Save FAISS index and metadata.json
faiss.write_index(index, 'index.faiss')
with open('metadata.json', 'w', encoding='utf-8') as f:
    json.dump(metadata, f, indent=4)

print(f"Ingested {len(all_chunks)} chunks. Index and metadata saved.")

# Verification Script
def verify_search(query, top_k=2):
    # Load resources
    loaded_index = faiss.read_index('index.faiss')
    with open('metadata.json', 'r', encoding='utf-8') as f:
        loaded_metadata = json.load(f)

    # Encode query
    query_vector = model.encode([query]).astype('float32')

    # Perform search
    distances, indices = loaded_index.search(query_vector, top_k)

    print(f"--- Search results for query: '{query}' ---")
    for rank, idx in enumerate(indices[0]):
        if idx < len(loaded_metadata):
            meta = loaded_metadata[idx]
            print(f"Rank {rank+1} (Distance: {distances[0][rank]:.4f})")
            print(f"Source File: {meta['source']} | Chunk Offset: {meta['offset']}")
            print(f"Excerpt: {meta['text'][:150]}...")
            print("-" * 40)

# Run a test query
verify_search("How should clinical surfaces be sanitized and how to wear PPE?")